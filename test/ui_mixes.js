const { chromium, devices } = require('playwright');
(async () => {
  const out = process.argv[2], port = process.argv[3];
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'], colorScheme: 'dark' });
  const p = await ctx.newPage();
  p.on('pageerror', e => console.log('PAGE ERROR', e.message));
  p.on('dialog', d => d.accept());
  await p.goto(`http://localhost:${port}/`);
  await p.screenshot({ path: `${out}/m0-header.png` });
  await p.click('#tab-mixes');
  await p.waitForSelector('#mx-subs .box, #mx-subs .empty');
  await p.screenshot({ path: `${out}/m1-tab.png`, fullPage: true });
  await p.fill('#link-url', 'https://podcasts.apple.com/za/podcast/deep-sessions/id123456?i=1000111');
  await p.click('text=Open');
  await p.waitForSelector('.ep');
  await p.screenshot({ path: `${out}/m2-link.png` });
  await p.click('#sheet .icon');
  await p.click('text=Open >> nth=1');
  await p.waitForSelector('.chk');
  await p.screenshot({ path: `${out}/m3-finder.png` });
  await p.click('#sheet .icon');
  await p.click('#tab-playlists');
  await p.click('text=Details >> nth=0');
  await p.waitForSelector('.trk');
  await p.screenshot({ path: `${out}/m4-job.png` });
  await p.click('text=Choose a copy >> nth=0');
  await p.waitForTimeout(5000);
  await p.screenshot({ path: `${out}/m5-choose.png` });
  await b.close();
})();
