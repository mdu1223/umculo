const { chromium, devices } = require('playwright');
(async () => {
  const out = process.argv[2], port = process.argv[3];
  const b = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
  const ctx = await b.newContext({ ...devices['iPhone 13'], colorScheme: 'dark', permissions: ['microphone'] });
  const p = await ctx.newPage();
  p.on('pageerror', e => console.log('PAGE ERROR', e.message));
  p.on('console', m => m.type() === 'error' && console.log('CONSOLE', m.text()));
  p.on('dialog', d => d.accept());
  const shot = async n => { await p.waitForTimeout(600); await p.screenshot({ path: `${out}/${n}.png` }); };
  const close = async () => { await p.evaluate(() => closeSheet()); await p.waitForTimeout(300); };
  await p.goto(`http://localhost:${port}/`);
  await shot('u1-home');
  await p.fill('#q', 'kabza'); await p.press('#q', 'Enter');
  await p.waitForSelector('.card', { timeout: 15000 }); await shot('u2-results');
  await p.click('button[title="Play the full song"] >> nth=0');
  await p.waitForTimeout(4000); await shot('u3-mini');
  await p.click('#mini .meta'); await shot('u4-player');
  console.log('player:', await p.evaluate(() => ({src: $("#player").src, paused: $("#player").paused, t: $("#player").currentTime, q: pq.length})));
  await close();
  await p.click('.stat-btn'); await p.waitForSelector('.check', { timeout: 60000 }); await shot('u5-status');
  await close();
  await p.click('.mic'); await shot('u6-listening');
  await p.waitForSelector('.found', { timeout: 30000 }); await shot('u7-found');
  await p.click('.gear'); await p.waitForSelector('input[name=stream_quality]');
  await p.evaluate(() => document.querySelector('input[name=stream_quality]').scrollIntoView({block: 'center'})); await shot('u8-streamq');
  await p.click('button.free:has-text("Share to Umculo")'); await p.waitForTimeout(500);
  await p.click('text=Create key'); await shot('u9-keys');
  await close();
  await p.click('#tab-playlists'); await p.waitForTimeout(1200); await shot('u10-playlists');
  await p.evaluate(() => document.querySelector('#imp-url').scrollIntoView({block: 'center'}));
  await p.fill('#imp-url', 'https://open.spotify.com/playlist/37i9dQZF1DXcBWIGoYBM5M'); await p.check('#imp-follow');
  await p.click('button:has-text("Import and fetch")'); await p.waitForTimeout(5000);
  await p.evaluate(() => window.scrollTo(0, 0)); await shot('u11-followed');
  await ctx.close(); await b.close();
})();
