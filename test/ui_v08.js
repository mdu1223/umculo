const { chromium, devices } = require('playwright');
(async () => {
  const out = process.argv[2], port = process.argv[3];
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'], colorScheme: 'dark', hasTouch: true });
  const p = await ctx.newPage();
  p.on('pageerror', e => console.log('PAGE ERROR', e.message));
  p.on('dialog', d => d.accept());
  const shot = async n => { await p.waitForTimeout(700); await p.screenshot({ path: `${out}/${n}.png` }); };
  const close = async () => { await p.evaluate(() => closeSheet()); await p.waitForTimeout(300); };
  await p.goto(`http://localhost:${port}/`);
  await p.click('#tab-foryou'); await p.waitForSelector('.rcard', { timeout: 20000 }); await p.waitForTimeout(1500); await shot('f1-foryou');
  await p.evaluate(() => document.querySelector('.genres').scrollIntoView({block: 'center'})); await shot('f2-explore');
  await p.click('.gchip >> nth=0'); await p.waitForSelector('#panel .trk', { timeout: 20000 }); await shot('f3-station');
  await close();
  await p.click('.rcard.new'); await shot('f4-templates');
  await p.click('.tpl >> nth=1'); await shot('f5-editor');
  await p.evaluate(() => document.querySelector('#panel').scrollTo(0, 2000)); await shot('f6-editor2');
  await p.click('text=Save and cook'); await p.waitForTimeout(4000); await shot('f7-recipe');
  await close();
  await p.click('#tab-playlists'); await p.waitForSelector('.sw', { timeout: 10000 }); await shot('p1-playlists');
  await p.click('.sw >> nth=0 >> .icon.more'); await shot('p2-swiped');
  await p.click('.sw.open .sa.del'); await p.waitForSelector('.btn.danger, .btn.ghost', { timeout: 10000 }); await shot('p3-delete');
  await close();
  await p.click('.sw >> nth=1 >> .meta'); await p.waitForSelector('#panel .trk'); await shot('p4-detail');
  await close();
  await p.click('#tab-requests'); await p.waitForTimeout(1000); await shot('q1-queue');
  await p.click('.stat-btn'); await p.waitForSelector('.check', { timeout: 60000 });
  await p.click('text=Logs'); await p.waitForTimeout(2500); await shot('s1-logs');
  await ctx.close(); await b.close();
})();
